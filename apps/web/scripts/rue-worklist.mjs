#!/usr/bin/env node
/**
 * Rusyn translator worklist — Sprint I18N-RUE (C1).
 *
 * Generates docs/RUE_TRANSLATION_WORKLIST.md from the message files: every
 * key whose rue.json value is still "" is listed with its Slovak source and
 * English reference, split into CLINICAL (patient-facing care, booking,
 * portal, telemedicine, wearables, emergency — a wrong rendering is a
 * safety problem; must be reviewed by a clinician-reader) and NON-CLINICAL
 * (chrome: nav, footer, brand, a11y controls). The app never generates
 * Rusyn text itself; an empty value renders the Slovak fallback.
 *
 * Usage: pnpm --filter=@ns/web worklist:rue   (rewrites the doc; commit it)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MSG = join(HERE, '..', 'src', 'messages');
const OUT = join(HERE, '..', '..', '..', 'docs', 'RUE_TRANSLATION_WORKLIST.md');
const load = (l) => JSON.parse(readFileSync(join(MSG, `${l}.json`), 'utf8'));
const sk = load('sk'), en = load('en'), rue = load('rue');

// Namespaces whose strings a patient reads while making a care decision.
const CLINICAL_NS = new Set(['emergency', 'callEmergency', 'central', 'book', 'bookHere', 'booking', 'telehealth', 'portal', 'onboarding', 'room', 'wearables', 'status', 'accepting', 'notAccepting', 'referralReq', 'beds', 'head', 'schedule', 'phone', 'location']);
// Keys that must be filled before the rue switcher entry goes live.
const GATE_NS = new Set(['brand', 'nav', 'navGroups', 'footer', 'a11y', 'login', 'more', 'backHome']);

const rows = [];
function walk(path, s, e, r) {
  for (const k of Object.keys(s)) {
    const p = path ? `${path}.${k}` : k;
    if (typeof s[k] === 'object') walk(p, s[k], e?.[k] ?? {}, r?.[k] ?? {});
    else rows.push({ key: p, ns: p.split('.')[0], sk: s[k], en: e?.[k] ?? '', rue: r?.[k] ?? '' });
  }
}
walk('', sk, en, rue);
const todo = rows.filter((r) => r.rue === '');
const done = rows.length - todo.length;
const esc = (t) => String(t).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (list) => ['| key | sk (source) | en (reference) |', '|---|---|---|', ...list.map((r) => `| \`${r.key}\` | ${esc(r.sk)} | ${esc(r.en)} |`)].join('\n');
const clinical = todo.filter((r) => CLINICAL_NS.has(r.ns));
const gate = todo.filter((r) => GATE_NS.has(r.ns));
const other = todo.filter((r) => !CLINICAL_NS.has(r.ns) && !GATE_NS.has(r.ns));

const md = `# Rusyn (\`rue\`) translation worklist

Generated by \`apps/web/scripts/rue-worklist.mjs\` — do not edit by hand; edit
\`apps/web/src/messages/rue.json\` and regenerate. **${done}/${rows.length} keys
translated, ${todo.length} open.** Any key still \`""\` renders the Slovak
fallback (\`i18n/request.ts\` merge); nothing here is machine-translated —
Prešov Rusyn is human-translated only (no MT provider supports it, and it
is a legal access requirement under Act 184/1999 on minority languages).

Target variety: Prešov Rusyn standard, Cyrillic (\`ґ є ї і ы ё ъ\`). Formal
register (vykanie) for patient-facing text, matching the Slovak source.

## 1. Chrome — fill these first (${gate.length} keys)

The Rusyn entry in the language switcher goes live only once this section
is complete: nav, footer, brand, accessibility controls. Non-clinical; a
bilingual reviewer suffices.

${table(gate)}

## 2. Clinical / safety-critical (${clinical.length} keys) — clinician-reader review required

Emergency numbers, booking, patient portal, telemedicine, remote monitoring,
clinic status. A wrong rendering here is a safety defect, not a typo: each
string needs sign-off by a Rusyn-reading clinician or medical translator,
named in the commit that fills it.

${table(clinical)}

## 3. Other UI strings (${other.length} keys)

${table(other)}

## 4. CMS clinical content (not keys — entries)

Departments, clinics, physicians, services, facilities, news, education
articles are Strapi entries. Rusyn versions are created as \`locale=rue\`
entries, start as drafts, and **cannot publish until a reviewer sets
\`review_status=approved\`** (the same gate as the MT locales —
\`REVIEW_GATED_LOCALES\` in \`packages/types\`, mirrored in
\`apps/cms/src/index.js\`). Source of truth for the Slovak text: the
\`sk\` entry of each item.
`;
writeFileSync(OUT, md);
console.log(`rue worklist: ${done}/${rows.length} translated, ${todo.length} open → ${OUT}`);
